"use client";

import { useState } from "react";
import { Check, Crown, IdCard, QrCode, X } from "lucide-react";
import { LogoBadge, SILVER_GRADIENT, SILVER_TEXT_DARK } from "./shared";
import type { PassportCardData } from "./types";

/** "NDY Passport" vertical card — redesigned 2026-11 to match the client's
 * Figma handoff ("NDYHUB — Logo 4K + Passport", passport-profile-mockup.png
 * in .figma-reference/, not committed): dark navy card, thin violet border,
 * "NDY PASSPORT" heading + logo badge header, photo + name/NDY ID, a silver
 * metallic tier pill (crown icon), and two full-width pill buttons ("My QR
 * Code" / "ID Card") in place of the old info-row list and static QR panel.
 *
 * Both buttons open a small in-card modal rather than navigating anywhere —
 * this component is also used, unauthenticated, by the public
 * /passport/[ndyId] page (app/passport/[ndyId]/page.tsx), which renders only
 * this one card with nothing else on the page to scroll/link to. Showing
 * the real QR (data.qrDataUrl, already generated by the caller) and a real
 * formatted ID view built from fields this card already has keeps both
 * buttons honestly wired on every page that renders this card, instead of
 * one of them only working on the authenticated dashboard. */
export function VerticalPassportCard({ data }: { data: PassportCardData }) {
  const [modal, setModal] = useState<"qr" | "id" | null>(null);

  const photoSrc =
    data.profilePhotoUrl ??
    `https://api.dicebear.com/9.x/initials/svg?seed=${encodeURIComponent(data.displayName)}&backgroundType=gradientLinear`;

  // Founding/leadership identities (Founder/CEO/etc., see common/ndy-id.util.ts)
  // take over the tier badge's label instead of the membership tier — same
  // priority this component always gave founding identity over an ordinary
  // membership tier, just restyled into the new silver pill instead of the
  // old "Genesis Identity" footer badge.
  const tierLabel = data.foundingIdentity
    ? (data.foundingIdentity.title ?? `NDY-${data.foundingIdentity.class}`)
    : (data.membershipTierLabel ?? "NDY HUB");

  return (
    <div
      className="relative w-full max-w-[420px] overflow-hidden rounded-[22px] border border-violet-400/25 p-6 shadow-[0_25px_60px_-15px_rgba(0,0,0,0.6)]"
      style={{ background: "#0f1420" }}
    >
      {/* Header: "NDY PASSPORT" heading + logo badge */}
      <div className="flex items-center justify-between gap-3">
        <h2 className="text-xl font-extrabold tracking-tight text-white">NDY PASSPORT</h2>
        <LogoBadge size={44} />
      </div>
      <div className="mt-4 h-px bg-white/10" />

      {/* Body: photo | divider | name + NDY ID ... tier pill */}
      <div className="mt-5 flex items-center justify-between gap-3">
        <div className="flex min-w-0 items-center gap-4">
          <div className="relative h-[72px] w-[72px] shrink-0">
            {/* eslint-disable-next-line @next/next/no-img-element -- data:/remote photoUrl, not a static asset next/image can optimize */}
            <img
              src={photoSrc}
              alt={data.displayName}
              width={72}
              height={72}
              className="h-full w-full rounded-2xl object-cover ring-1 ring-white/10"
            />
            {data.verified && (
              <span
                className="absolute -right-1 -bottom-1 flex h-5 w-5 items-center justify-center rounded-full bg-[#2b8fff] ring-2"
                style={{ boxShadow: "0 0 0 2px #0f1420" }}
                title="Verified"
              >
                <Check className="h-3 w-3 text-white" strokeWidth={3} />
              </span>
            )}
          </div>

          <div className="h-12 w-px shrink-0 bg-white/15" />

          <div className="min-w-0">
            <div className="truncate text-lg font-bold text-white">{data.displayName}</div>
            <div className="mt-0.5 truncate text-sm font-semibold text-violet-400">
              {data.ndyId}
            </div>
          </div>
        </div>

        <div
          className="flex shrink-0 items-center gap-2 rounded-full px-3.5 py-2 text-sm font-bold whitespace-nowrap"
          style={{ background: SILVER_GRADIENT, color: SILVER_TEXT_DARK }}
        >
          <Crown className="h-4 w-4 shrink-0" strokeWidth={2.25} />
          <span className="h-4 w-px shrink-0" style={{ background: "rgba(15,20,32,0.3)" }} />
          <span className="truncate">{tierLabel}</span>
        </div>
      </div>

      {/* Two full-width pill buttons: My QR Code / ID Card */}
      <div className="mt-5 grid grid-cols-2 gap-3">
        <button
          type="button"
          onClick={() => setModal("qr")}
          className="flex items-center justify-center gap-2 rounded-xl border border-violet-400/40 py-3 text-sm font-semibold text-white hover:bg-white/5"
        >
          <QrCode className="h-4 w-4" strokeWidth={2} />
          My QR Code
        </button>
        <button
          type="button"
          onClick={() => setModal("id")}
          className="flex items-center justify-center gap-2 rounded-xl border border-violet-400/40 py-3 text-sm font-semibold text-white hover:bg-white/5"
        >
          <IdCard className="h-4 w-4" strokeWidth={2} />
          ID Card
        </button>
      </div>

      {modal && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-6"
          onClick={() => setModal(null)}
        >
          <div
            className="relative w-full max-w-xs rounded-2xl border border-violet-400/30 bg-[#0f1420] p-6 text-center shadow-2xl"
            onClick={(e) => e.stopPropagation()}
          >
            <button
              type="button"
              onClick={() => setModal(null)}
              aria-label="Close"
              className="absolute top-3 right-3 text-slate-400 hover:text-white"
            >
              <X className="h-4 w-4" />
            </button>

            {modal === "qr" ? (
              <>
                <div className="mx-auto flex h-[180px] w-[180px] items-center justify-center rounded-xl bg-white p-3">
                  {data.qrDataUrl ? (
                    // eslint-disable-next-line @next/next/no-img-element -- data: URL
                    <img src={data.qrDataUrl} alt="Scan to connect" width={156} height={156} />
                  ) : (
                    <span className="text-xs text-black/40">Generating…</span>
                  )}
                </div>
                <p className="mt-3 text-sm text-slate-300">Scan to connect</p>
                <p className="mt-0.5 text-xs text-slate-500">{data.ndyId}</p>
              </>
            ) : (
              <>
                <div className="mx-auto h-20 w-20">
                  {/* eslint-disable-next-line @next/next/no-img-element -- data:/remote photoUrl */}
                  <img
                    src={photoSrc}
                    alt={data.displayName}
                    width={80}
                    height={80}
                    className="h-full w-full rounded-2xl object-cover ring-1 ring-white/10"
                  />
                </div>
                <div className="mt-3 text-base font-bold text-white">{data.displayName}</div>
                <div className="text-sm font-semibold text-violet-400">{data.ndyId}</div>
                <div
                  className="mx-auto mt-3 inline-flex items-center gap-2 rounded-full px-3.5 py-1.5 text-xs font-bold"
                  style={{ background: SILVER_GRADIENT, color: SILVER_TEXT_DARK }}
                >
                  <Crown className="h-3.5 w-3.5" strokeWidth={2.25} />
                  {tierLabel}
                </div>
              </>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
